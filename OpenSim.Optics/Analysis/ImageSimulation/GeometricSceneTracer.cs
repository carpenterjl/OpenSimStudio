using OpenSim.Core.Numerics;
using OpenSim.Optics.Analysis.Rays;
using OpenSim.Optics.Sequential;
using OpenSim.Optics.Wavefront;

namespace OpenSim.Optics.Analysis.ImageSimulation;

/// <summary>How the source radiates (help, "Geometric Image Analysis": "The uniform setting
/// weights rays equally. Lambertian weights rays by the cosine of the angle the ray makes with
/// local normal of the object surface").</summary>
public enum SceneSource
{
    Uniform = 0,
    Lambertian = 1,
}

/// <summary>One colour of a ray-traced scene: a picture map traced at a wavelength row with a
/// weight per unit pixel value.</summary>
public sealed record TracedChannel(int SceneChannel, int Wavelength, double Weight, string Name);

/// <summary>What <see cref="GeometricSceneTracer.Trace"/> traces.</summary>
public sealed record GeometricSceneRequest
{
    public required SceneImage Scene { get; init; }
    /// <summary>The 0-based field row the picture is centred on.</summary>
    public required int Field { get; init; }
    /// <summary>One pixel's size in field units (degrees, or meters for heights).</summary>
    public required double PixelField { get; init; }
    public required IReadOnlyList<TracedChannel> Channels { get; init; }
    /// <summary>About this many rays shared by pixel value × weight, at least one per lit pixel
    /// and colour (Geometric Image Analysis); null to use <see cref="RaysPerPixel"/>.</summary>
    public int? TotalRays { get; init; }
    /// <summary>Rays per lit pixel and colour (Geometric Bitmap Image Analysis).</summary>
    public int RaysPerPixel { get; init; } = 1;
    /// <summary>Odd parity: the picture reversed top to bottom.</summary>
    public bool OddParity { get; init; }
    /// <summary>The picture turned counter-clockwise by this many degrees before tracing.</summary>
    public double RotationDegrees { get; init; }
    public SceneSource Source { get; init; } = SceneSource.Uniform;
    /// <summary>The surface the rays are read at.</summary>
    public required int Surface { get; init; }
    /// <summary>Drop a ray that passes the surface but is stopped later (help: "Delete Vignetted").</summary>
    public bool DeleteVignetted { get; init; }
    /// <summary>Drop rays with n·sin θ above this at the surface (θ from its local z axis); 0 for none.</summary>
    public double NumericalAperture { get; init; }
    public int? MaxDegreeOfParallelism { get; init; }
}

/// <summary>One detected ray: where it met the surface (local frame, meters), its colour and weight.</summary>
public readonly record struct SceneHit(double X, double Y, int Channel, double Weight);

/// <summary>The traced scene.</summary>
public sealed record GeometricSceneResult
{
    public required IReadOnlyList<SceneHit> Hits { get; init; }
    /// <summary>Σ weight of every ray launched (vignetted or not), per colour.</summary>
    public required IReadOnlyList<double> Launched { get; init; }
    public required long RaysLaunched { get; init; }
    public required IReadOnlyList<string> Failures { get; init; }
    /// <summary>The centre field's chief ray at the surface, per colour (NaN when it fails).</summary>
    public required IReadOnlyList<(double X, double Y)> Chief { get; init; }
}

/// <summary>
/// The rays of an extended scene (OP-42), as OpticStudio's Geometric Image Analysis and
/// Geometric Bitmap Image Analysis trace them (help pages of those names): "The rays generated by
/// each pixel are chosen randomly from coordinates within the pixel cell. The entrance pupil
/// coordinates are also chosen randomly for each ray. The distribution of rays is uniform over
/// the pixel and over the circular paraxial entrance pupil". Here, as in OP-41's extended source,
/// the positions come from a 4-D Sobol sequence (u, v in the pixel; ρ = √s, θ = 2πt in the pupil)
/// so a result repeats exactly. Pixel (r, c) of a W × H picture spans the field offsets
/// ((c + u − W/2)·δ, (H/2 − r − v)·δ) about the chosen field, δ the pixel's field size; odd parity
/// reverses the rows, and the rotation turns the offsets counter-clockwise by the angle (help:
/// "The algorithm actually rotates the object before tracing the rays"). A ray's weight is its
/// pixel value × the colour's weight over the pixel's ray count, times the pupil apodization
/// squared and, for a Lambertian source, the cosine of its launch direction to the object normal
/// (the z axis). The picture's rotated corners are appended to the fields (weight 0) so every
/// point normalises inside them; vignetting factors cannot be interpolated across the picture and
/// are refused (remove them first).
/// </summary>
public static class GeometricSceneTracer
{
    public const long MaximumRays = 20_000_000;

    public static GeometricSceneResult Trace(SequentialLens lens, OpticalSystemData system, GeometricSceneRequest request, string who,
        CancellationToken cancellation = default)
    {
        ArgumentNullException.ThrowIfNull(lens);
        ArgumentNullException.ThrowIfNull(system);
        ArgumentNullException.ThrowIfNull(request);
        var scene = request.Scene;
        int W = scene.Width, H = scene.Height;
        if (request.Field < 0 || request.Field >= system.Fields.Points.Count)
            throw new ArgumentException($"{who}: field {request.Field + 1} is not one of the {system.Fields.Points.Count} fields.");
        if (!(request.PixelField > 0) || !double.IsFinite(request.PixelField))
            throw new ArgumentException($"{who}: the field size must be positive.");
        if (!double.IsFinite(request.RotationDegrees)) throw new ArgumentException($"{who}: the rotation must be a number.");
        if (!(request.NumericalAperture >= 0)) throw new ArgumentException($"{who}: the NA must be 0 (none) or positive.");
        if (system.Fields.Points.Any(p => p.IsVignetted))
            throw new InvalidOperationException($"{who}: the fields have vignetting factors, which cannot be interpolated across the picture; turn on \"Remove vignetting factors\".");
        if (request.Channels.Count == 0) throw new ArgumentException($"{who}: at least one colour.");
        if (request.TotalRays is null && request.RaysPerPixel < 1) throw new ArgumentException($"{who}: at least one ray per pixel.");
        int surface = request.Surface;
        if (surface < 1 || surface > lens.ImageIndex) throw new ArgumentException($"{who}: surface {surface} is not one of 1 to {lens.ImageIndex}.");

        var centre = system.Fields.Points[request.Field];
        double d = request.PixelField;
        var (sin, cos) = OpticsConventions.SinCosDegrees(request.RotationDegrees);
        (double X, double Y) Offset(double u, double v) => (u * cos - v * sin, u * sin + v * cos);
        var corners = new[] { (-1, -1), (1, -1), (-1, 1), (1, 1) }.Select(s =>
        {
            var (ox, oy) = Offset(s.Item1 * W * d / 2, s.Item2 * H * d / 2);
            return new FieldPoint { X = centre.X + ox, Y = centre.Y + oy, Weight = 0 };
        }).ToArray();
        if (FieldTypes.IsAngle(system.Fields.Type) && corners.Any(c => !(Math.Abs(c.X) < 90) || !(Math.Abs(c.Y) < 90)))
            throw new ArgumentException($"{who}: the picture reaches beyond 90° from the axis; shrink the field size.");
        var extended = system with { Fields = system.Fields with { Points = system.Fields.Points.Concat(corners).ToArray() } };
        var scale = extended.Fields.Scale;
        var launcher = new RayLauncher(lens, extended);
        var apodization = PsfEngine.Apodization(lens, system, who);
        var channels = request.Channels;
        var traces = channels.Select(c => SequentialTrace.Create(lens, extended, c.Wavelength)).ToArray();
        foreach (var c in channels)
            if (!(c.Weight >= 0) || !double.IsFinite(c.Weight)) throw new ArgumentException($"{who}: colour {c.Name}'s weight is {c.Weight}; it must be finite and not negative.");

        // Rays per pixel and colour, and the running Sobol index each (colour, row) starts at.
        int nc = channels.Count;
        double total = 0;
        for (int ci = 0; ci < nc; ci++)
            foreach (var v in scene.Channels[channels[ci].SceneChannel]) total += v * channels[ci].Weight;
        if (!(total > 0)) throw new ArgumentException($"{who}: the picture has no lit pixel in a colour of non-zero weight, so there is no light.");
        var counts = new int[nc][,];
        var starts = new long[nc * H + 1];
        long rays = 0;
        for (int ci = 0; ci < nc; ci++)
        {
            var map = scene.Channels[channels[ci].SceneChannel];
            counts[ci] = new int[H, W];
            for (int r = 0; r < H; r++)
            {
                starts[ci * H + r] = rays;
                for (int c = 0; c < W; c++)
                {
                    double e = map[r, c] * channels[ci].Weight;
                    if (!(e > 0)) continue;
                    int k = request.TotalRays is int t ? (int)Math.Max(1, Math.Round(t * e / total)) : request.RaysPerPixel;
                    counts[ci][r, c] = k;
                    rays += k;
                }
                if (rays > MaximumRays)
                    throw new ArgumentException($"{who}: the picture needs more than {MaximumRays} rays; lower the ray count or use a smaller picture.");
            }
        }
        starts[nc * H] = rays;

        var sobol = new SobolSequence(4);
        var options = new TraceOptions();
        var slots = ParallelSlots.Compute(nc * H, request.MaxDegreeOfParallelism, slot =>
        {
            int ci = slot / H, r = slot % H;
            var ch = channels[ci];
            var map = scene.Channels[ch.SceneChannel];
            var hits = new List<SceneHit>();
            var failures = new List<SampledRay>();
            double launched = 0;
            long index = starts[slot] + 1; // index 0 of the Sobol sequence is the corner (0, 0, 0, 0)
            Span<double> q = stackalloc double[4];
            int row = request.OddParity ? H - 1 - r : r;
            for (int c = 0; c < W; c++)
            {
                int k = counts[ci][r, c];
                if (k == 0) continue;
                cancellation.ThrowIfCancellationRequested();
                double weight = map[r, c] * ch.Weight / k;
                for (int j = 0; j < k; j++, index++)
                {
                    sobol.Point(index, q);
                    var (ox, oy) = Offset((c + q[0] - W / 2.0) * d, (H / 2.0 - row - q[1]) * d);
                    double rho = Math.Sqrt(q[2]), theta = 2 * Math.PI * q[3];
                    double px = rho * Math.Cos(theta), py = rho * Math.Sin(theta);
                    var (hx, hy) = OpticsConventions.NormalizeField((centre.X + ox, centre.Y + oy), scale);
                    var launch = launcher.Launch(traces[ci], hx, hy, px, py);
                    double a = apodization(rho);
                    double w = weight * a * a * (request.Source == SceneSource.Lambertian ? Math.Abs(launch.Direction.Z) : 1);
                    launched += w;
                    var path = traces[ci].TracePath(launch, options);
                    SurfaceHit? hit = null;
                    foreach (var h in path.Hits) if (h.Surface == surface) { hit = h; break; }
                    bool passedSurface = hit is not null && hit.Status == RayStatus.Ok;
                    if (!passedSurface || (request.DeleteVignetted && !path.Final.IsOk))
                    {
                        failures.Add(new SampledRay(px, py, hit?.Status, path.Final.Status, path.Final.FailedAtSurface,
                            SampledRay.NaNVector, SampledRay.NaNVector));
                        continue;
                    }
                    if (request.NumericalAperture > 0)
                    {
                        var dir = hit!.Direction;
                        double na = Math.Abs(hit.IndexAfter) * Math.Sqrt(dir.X * dir.X + dir.Y * dir.Y);
                        if (na > request.NumericalAperture) continue;
                    }
                    hits.Add(new SceneHit(hit!.Position.X, hit.Position.Y, ci, w));
                }
            }
            return (hits, failures, launched);
        }, cancellation);

        var all = new List<SceneHit>();
        var launchedByChannel = new double[nc];
        var failed = new List<SampledRay>();
        for (int s = 0; s < slots.Length; s++)
        {
            all.AddRange(slots[s].hits);
            failed.AddRange(slots[s].failures);
            launchedByChannel[s / H] += slots[s].launched;
        }
        var chief = new List<(double, double)>();
        var (chx, chy) = OpticsConventions.NormalizeField((centre.X, centre.Y), scale);
        for (int ci = 0; ci < nc; ci++)
        {
            var ray = RaySampler.AtSurface(traces[ci], launcher, chx, chy, 0, 0, surface, new TraceOptions { IgnoreApertures = true });
            chief.Add(ray.AtSurface is null ? (double.NaN, double.NaN) : (ray.Position.X, ray.Position.Y));
        }
        return new GeometricSceneResult
        {
            Hits = all, Launched = launchedByChannel, RaysLaunched = rays, Failures = RaySampler.DescribeFailures(failed, countLaterFailures: true),
            Chief = chief,
        };
    }

    /// <summary>
    /// The hits binned on a detector of nx × ny pixels of size px × py centred on (cx, cy), row 0
    /// the top (+y): each ray's weight in the pixel it strikes, or, with
    /// <paramref name="interpolate"/>, shared bilinearly among the four pixels whose centres
    /// surround it (help, "Use Pixel Interpolation": "ray energy is distributed among adjacent
    /// pixels according to the distance from where the ray lands to the center of the pixel").
    /// Returns one map per colour and the weight that landed on the detector per colour.
    /// </summary>
    public static (double[][,] Maps, double[] Detected) Bin(IReadOnlyList<SceneHit> hits, int channels, double cx, double cy,
        int nx, int ny, double px, double py, bool interpolate)
    {
        var maps = Enumerable.Range(0, channels).Select(_ => new double[ny, nx]).ToArray();
        var detected = new double[channels];
        double x0 = cx - nx * px / 2, y1 = cy + ny * py / 2;
        foreach (var h in hits)
        {
            double fc = (h.X - x0) / px, fr = (y1 - h.Y) / py; // in pixel units from the top-left corner
            if (!(fc >= 0 && fc < nx && fr >= 0 && fr < ny)) continue;
            detected[h.Channel] += h.Weight;
            var map = maps[h.Channel];
            if (!interpolate)
            {
                map[(int)fr, (int)fc] += h.Weight;
                continue;
            }
            double u = fc - 0.5, v = fr - 0.5;
            int c0 = (int)Math.Floor(u), r0 = (int)Math.Floor(v);
            double tu = u - c0, tv = v - r0;
            // Shares that would fall off the detector go to the nearest pixel inside, so the
            // detected weight is kept.
            void Add(int r, int c, double s)
            {
                r = Math.Clamp(r, 0, ny - 1);
                c = Math.Clamp(c, 0, nx - 1);
                map[r, c] += s;
            }
            Add(r0, c0, h.Weight * (1 - tu) * (1 - tv));
            Add(r0, c0 + 1, h.Weight * tu * (1 - tv));
            Add(r0 + 1, c0, h.Weight * (1 - tu) * tv);
            Add(r0 + 1, c0 + 1, h.Weight * tu * tv);
        }
        return (maps, detected);
    }
}
