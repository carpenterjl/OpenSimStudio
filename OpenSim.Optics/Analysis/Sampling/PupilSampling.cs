using OpenSim.Core.Numerics;
using OpenSim.Optics.Sequential;

namespace OpenSim.Optics.Analysis.Sampling;

/// <summary>How rays are arranged on the normalised pupil (OpticStudio's "Pattern" setting of
/// the spot diagrams).</summary>
public enum PupilPattern
{
    /// <summary>A central ray and rings of 6, 12, 18, … rays.</summary>
    Hexapolar = 0,

    /// <summary>A square grid of n × n points, those inside the unit circle kept.</summary>
    Square = 1,

    /// <summary>Pseudo-random points, uniform over the unit disk, from a fixed seed.</summary>
    Dithered = 2,
}

/// <summary>
/// Pupil sampling for the ray and spot analyses (OP-34): the hexapolar, square and dithered
/// patterns of OpticStudio's spot diagrams, as normalised pupil points (Px, Py) with
/// Px² + Py² ≤ 1 (docs/Optics-Conventions.md §7, §25). Every pattern is a pure function of its
/// arguments: the same call gives the same points, bit for bit, on any machine.
/// <para>
/// Sources (Ansys OpticStudio 2025 R2 help, ansyshelp.ansys.com, OpticStudio_Help/topics; copies
/// in <c>plans/sources/optics/op-34-help/</c>, not in the repository):
/// "Hexapolar Rings" (Conventions and Definitions): "The first ring contains 6 rays, oriented
/// every 60 degrees around the entrance pupil with the first ray starting at 0 degrees (on the
/// x-axis of the pupil)", "Each subsequent ring has 6 more rays than the previous ring", and a
/// sampling of 5 is 1 + 6 + 12 + 18 + 24 + 30 = 91 rays. "Standard Spot Diagram": the ray
/// density is "the number of Hexapolar Rings to be traced if a Hexapolar or Dithered Pattern is
/// selected, or the Number of Rays across the Width and Height if a Rectangular Pattern is
/// selected", its minimum is 3, and dithered spot diagrams "are generated by pseudo-random
/// rays".
/// </para>
/// <para>
/// What the help does not state, and this program chooses: hexapolar ring k of N lies at radius
/// k/N (equally spaced rings, so with 6k rays per ring the density per unit area is nearly
/// even); the square grid is cell-centred, points spaced 2/n apart (<see cref="BatchTracer"/>'s
/// <c>SquareGrid</c>, so an even n has no ray at the centre); a dithered pattern of N rings has
/// as many rays as the hexapolar one, 1 + 3N(N + 1), drawn uniformly over the disk as
/// (√u cos 2πv, √u sin 2πv) from <see cref="SplitMix64"/> seeded with <see cref="DitherSeed"/>,
/// so a dithered spot diagram is the same on every run.
/// </para>
/// </summary>
public static class PupilSampling
{
    /// <summary>The fixed seed of the dithered pattern.</summary>
    public const long DitherSeed = 0x0534_D17E_12ED;

    /// <summary>The smallest ray density the spot diagrams accept (the help's "The Ray Density
    /// Minimum Value is 3").</summary>
    public const int MinimumSpotDensity = 3;

    /// <summary>The rays of a hexapolar pattern of <paramref name="rings"/> rings, 1 + 3N(N + 1).</summary>
    public static int HexapolarCount(int rings)
    {
        if (rings < 0) throw new ArgumentOutOfRangeException(nameof(rings), rings, "The number of hexapolar rings cannot be negative.");
        return 1 + 3 * rings * (rings + 1);
    }

    /// <summary>The central ray, then ring k = 1 … N at radius k/N with 6k rays at angles
    /// 2πj/(6k), j = 0 … 6k − 1, the first on +x.</summary>
    public static IReadOnlyList<(double Px, double Py)> Hexapolar(int rings)
    {
        var points = new List<(double, double)>(HexapolarCount(rings)) { (0, 0) };
        for (int k = 1; k <= rings; k++)
        {
            double r = (double)k / rings;
            int count = 6 * k;
            for (int j = 0; j < count; j++)
            {
                double angle = 2 * Math.PI * j / count;
                points.Add((r * Math.Cos(angle), r * Math.Sin(angle)));
            }
        }
        return points;
    }

    /// <summary>A cell-centred n × n grid, those points inside the unit circle
    /// (<see cref="BatchTracer.SquareGrid"/>).</summary>
    public static IReadOnlyList<(double Px, double Py)> Square(int raysAcross) => BatchTracer.SquareGrid(raysAcross);

    /// <summary>1 + 3N(N + 1) pseudo-random points uniform over the unit disk, from
    /// <paramref name="seed"/> (default <see cref="DitherSeed"/>).</summary>
    public static IReadOnlyList<(double Px, double Py)> Dithered(int rings, long seed = DitherSeed)
    {
        int count = HexapolarCount(rings);
        var random = new SplitMix64(seed);
        var points = new (double, double)[count];
        for (int i = 0; i < count; i++)
        {
            double r = Math.Sqrt(random.NextDouble());
            double angle = 2 * Math.PI * random.NextDouble();
            points[i] = (r * Math.Cos(angle), r * Math.Sin(angle));
        }
        return points;
    }

    /// <summary>The points of a pattern at a ray density (rings, or rays across for the square grid).</summary>
    public static IReadOnlyList<(double Px, double Py)> Points(PupilPattern pattern, int density) => pattern switch
    {
        PupilPattern.Hexapolar => Hexapolar(density),
        PupilPattern.Square => Square(density),
        PupilPattern.Dithered => Dithered(density),
        _ => throw new ArgumentOutOfRangeException(nameof(pattern), pattern, "Unknown pupil pattern."),
    };

    /// <summary>One line saying how the pupil was sampled, for an analysis's assumptions.</summary>
    public static string Describe(PupilPattern pattern, int density, int count) => pattern switch
    {
        PupilPattern.Hexapolar => $"Pupil sampling: hexapolar, {density} rings at radii k/{density} (6k rays in ring k, the first on +x), {count} rays per field and wavelength.",
        PupilPattern.Square => $"Pupil sampling: square, {density} × {density} cell-centred grid, the {count} points inside the unit pupil.",
        PupilPattern.Dithered => $"Pupil sampling: dithered, {count} pseudo-random points uniform over the pupil (as many as {density} hexapolar rings), fixed seed {DitherSeed}, so the pattern is the same on every run.",
        _ => throw new ArgumentOutOfRangeException(nameof(pattern), pattern, "Unknown pupil pattern."),
    };

    /// <summary>The 2n + 1 points k/n, k = −n … n, of a ray fan (OpticStudio's "Number of
    /// Rays", "the number of rays traced on each side of the origin of the plot").</summary>
    public static IReadOnlyList<double> Fan(int raysEachSide)
    {
        if (raysEachSide < 1) throw new ArgumentOutOfRangeException(nameof(raysEachSide), raysEachSide, "A ray fan needs at least one ray on each side of the origin.");
        var points = new double[2 * raysEachSide + 1];
        for (int k = -raysEachSide; k <= raysEachSide; k++) points[k + raysEachSide] = (double)k / raysEachSide;
        return points;
    }

    /// <summary>The (2n + 1) × (2n + 1) grid (i/n, k/n) inside the unit circle: the footprint
    /// diagram's ray density, "the number of rays traced across the half pupil; a setting of 10
    /// will trace a grid of 21 x 21 rays" (help, "Footprint Diagram").</summary>
    public static IReadOnlyList<(double Px, double Py)> HalfPupilGrid(int raysAcrossHalf)
    {
        if (raysAcrossHalf < 1) throw new ArgumentOutOfRangeException(nameof(raysAcrossHalf), raysAcrossHalf, "The grid needs at least one ray across the half pupil.");
        var points = new List<(double, double)>();
        int n = raysAcrossHalf;
        for (int i = n; i >= -n; i--)
            for (int k = -n; k <= n; k++)
            {
                double px = (double)k / n, py = (double)i / n;
                if (px * px + py * py <= 1) points.Add((px, py));
            }
        return points;
    }
}
